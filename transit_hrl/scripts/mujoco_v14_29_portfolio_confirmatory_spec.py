def validate() -> None:
    roles = (
        CRITIC_TRAIN_ROOTS,
        CRITIC_HOLDOUT_ROOTS,
        DESIGN_ROOTS,
        VALIDATION_ROOTS,
    )
    flattened = [int(root) for role in roles for root in role]
    anchor_roles = (
        anchors.OPTIMIZER_SEEDS
        + anchors.PRETRAIN_SEEDS
        + anchors.PRETRAIN_SELECTION_SEEDS
        + anchors.DEVELOPMENT_EVALUATION_SEEDS
    )
    if len(flattened) != 96 or len(flattened) != len(set(flattened)):
        raise RuntimeError("v14.29 requires 96 unique portfolio roots")
    if set(flattened) & set(anchor_roles):
        raise RuntimeError("v14.29 portfolio and anchor roles overlap")
    previous = set(
        predecessor.CRITIC_TRAIN_ROOTS
        + predecessor.CRITIC_HOLDOUT_ROOTS
        + predecessor.DESIGN_ROOTS
        + predecessor.VALIDATION_ROOTS
    )
    if previous & set(flattened):
        raise RuntimeError("v14.29 roots overlap v14.28 preflight")
    if EXPECTED_CELL_COUNT != 48 or len(OPTIMIZER_SEEDS) != 16:
        raise RuntimeError("v14.29 requires forty-eight confirmatory cells")
    if EXPECTED_CRITIC_TRAIN_PATH_COUNT != 320:
        raise RuntimeError("v14.29 critic train path count drifted")
    if EXPECTED_CRITIC_HOLDOUT_PATH_COUNT != 320:
        raise RuntimeError("v14.29 critic holdout path count drifted")
    if EXPECTED_DESIGN_PATH_COUNT != 128 or EXPECTED_VALIDATION_PATH_COUNT != 128:
        raise RuntimeError("v14.29 design/validation path count drifted")
    if EXPECTED_DESIGN_FOLD_PATH_COUNT != 64:
        raise RuntimeError("v14.29 requires two 64-path design folds")
    if EXPECTED_CANDIDATE_COUNT != 15 or WORKERS != CPU_PER_TASK:
        raise RuntimeError("v14.29 candidate or scheduler contract drifted")


validate()
